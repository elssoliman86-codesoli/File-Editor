class DocumentTemplate {
  const DocumentTemplate({
    required this.id,
    required this.titleKey,
    required this.description,
    required this.content,
  });
  final String id;
  final String titleKey;
  final String description;
  final String content;

  List<Map<String, dynamic>> operations({bool rtl = true}) {
    final operations = <Map<String, dynamic>>[];
    final lines = content.split('\n');
    for (var i = 0; i < lines.length; i++) {
      final line = lines[i];
      if (line.isEmpty) {
        operations.add({
          'insert': '\n',
          'attributes': {'direction': rtl ? 'rtl' : null}
            ..removeWhere((k, v) => v == null),
        });
        continue;
      }
      final heading = line.startsWith('# ');
      final subheading = line.startsWith('## ');
      final bullet = line.startsWith('• ');
      final text = line.replaceFirst(RegExp(r'^#{1,2} |^• '), '');
      operations.add({
        'insert': text,
        'attributes': {
          if (heading || subheading) 'bold': true,
          if (heading) 'size': '24',
          if (subheading) 'size': '19',
        },
      });
      operations.add({
        'insert': '\n',
        'attributes': {
          if (heading) 'header': 1,
          if (subheading) 'header': 2,
          if (bullet) 'list': 'bullet',
          if (rtl) 'direction': 'rtl',
        },
      });
    }
    return operations;
  }
}

